"""
Exact convex polyhedra over the rationals (double description method).

This module replaces the APRON/NewPolka library used by the OCaml FuncTion.
Everything is computed with Python integers, so results are exact.

Representation (n = number of dimensions):
  - constraints are integer vectors (a_1, ..., a_n, c) meaning
        a_1*x_1 + ... + a_n*x_n + c >= 0     (inequalities)
        a_1*x_1 + ... + a_n*x_n + c  = 0     (equalities)
  - generators are homogenized integer vectors (x_1, ..., x_n, t) with t >= 0:
        t > 0 is the vertex (x_1/t, ..., x_n/t), t = 0 is a ray;
    lines (bidirectional rays) are kept separately.

Both representations are kept minimal at all times.

Why two representations? Each operation is easy on one of them:
  - intersection (meet, filter) and pre-image (backward assignment):
    concatenate/substitute the constraints;
  - convex hull (join), image (forward assignment) and projection:
    union/transform the generators;
  - inclusion P ⊑ Q: check that every generator of P satisfies every
    constraint of Q.
The double description method (Motzkin et al. 1953, Chernikova 1965) converts
one representation into the other. Thanks to the homogenization (adding the
coordinate t for the constant term), a polyhedron becomes a cone, and the same
algorithm converts constraints into generators and back (by duality).
"""

from fractions import Fraction
from math import gcd


def normalize(v):
    """Divides an integer vector by the gcd of its entries."""
    g = 0
    for x in v:
        g = gcd(g, x)
        if g == 1:
            return tuple(v)
    if g > 1:
        return tuple(x // g for x in v)
    return tuple(v)


def dot(a, b):
    return sum(x * y for x, y in zip(a, b))


def _dd(dim, eqs, ineqs):
    """Double description conversion.

    Given the cone C = { y | a.y = 0 for a in eqs, a.y >= 0 for a in ineqs }
    in dimension dim, returns its minimal generators (lines, rays).

    The algorithm starts from the whole space (generated by the lines e_1,
    ..., e_dim) and adds the constraints one at a time, updating the
    generators:
      - if some line l is not orthogonal to the constraint a, it is used to
        make all other generators orthogonal to a (Gaussian elimination);
        l itself becomes a ray on the side where a.l > 0 (or disappears for
        an equality);
      - otherwise, the rays are split according to the sign of a.r: the rays
        with a.r >= 0 are kept, and each pair of *adjacent* rays (p, n) with
        a.p > 0 > a.n is combined into a new ray on the hyperplane a.y = 0.
        Two rays are adjacent if no other ray saturates all the constraints
        they both saturate (combinatorial test), which avoids generating
        redundant rays.
    The saturated constraints of each ray are kept as a bitmask.
    """
    lines = [tuple(1 if i == j else 0 for j in range(dim)) for i in range(dim)]
    rays = []  # pairs (ray, bitmask of the saturated constraints)
    k = 0
    for is_eq, a in [(True, e) for e in eqs] + [(False, i) for i in ineqs]:
        bit = 1 << k
        k += 1
        # look for a line that is not orthogonal to the constraint
        pivot = None
        for idx, l in enumerate(lines):
            if dot(a, l) != 0:
                pivot = idx
                break
        if pivot is not None:
            l = lines.pop(pivot)
            sl = dot(a, l)
            if sl < 0:
                l = tuple(-x for x in l)
                sl = -sl
            nlines = []
            for m in lines:
                sm = dot(a, m)
                if sm:
                    m = normalize(tuple(sl * x - sm * y for x, y in zip(m, l)))
                nlines.append(m)
            lines = nlines
            nrays = []
            for r, sat in rays:
                sr = dot(a, r)
                if sr:
                    r = normalize(tuple(sl * x - sr * y for x, y in zip(r, l)))
                nrays.append((r, sat | bit))
            if not is_eq:  # the line becomes a ray saturating all previous constraints
                nrays.append((l, bit - 1))
            rays = nrays
            continue
        pos, zero, neg = [], [], []
        for r, sat in rays:
            s = dot(a, r)
            if s > 0:
                pos.append((r, sat, s))
            elif s < 0:
                neg.append((r, sat, s))
            else:
                zero.append((r, sat))
        nrays = [(r, sat | bit) for r, sat in zero]
        if not is_eq:
            nrays.extend((r, sat) for r, sat, _ in pos)
        if pos and neg:
            threshold = dim - len(lines) - 2
            for p, sp, vp in pos:
                for n, sn, vn in neg:
                    common = sp & sn
                    if common.bit_count() < threshold:
                        continue
                    adjacent = True
                    for r, sr in rays:
                        if r is p or r is n:
                            continue
                        if sr & common == common:
                            adjacent = False
                            break
                    if adjacent:
                        v = normalize(tuple(vp * x - vn * y for x, y in zip(n, p)))
                        nrays.append((v, common | bit))
        rays = nrays
    return lines, [r for r, _ in rays]


class Polyhedron:
    """An immutable closed convex polyhedron in Q^n."""

    __slots__ = ('n', 'eqs', 'ineqs', 'lines', 'rays', 'empty')

    def __init__(self, n, eqs, ineqs, lines, rays, empty):
        self.n = n
        self.eqs = eqs
        self.ineqs = ineqs
        self.lines = lines
        self.rays = rays
        self.empty = empty

    # construction

    @staticmethod
    def universe(n):
        lines = [tuple(1 if i == j else 0 for j in range(n + 1)) for i in range(n)]
        vertex = (0,) * n + (1,)
        return Polyhedron(n, [], [], lines, [vertex], False)

    @staticmethod
    def bottom(n):
        return Polyhedron(n, [], [(0,) * n + (-1,)], [], [], True)

    @staticmethod
    def from_constraints(n, eqs=(), ineqs=()):
        eqs = [normalize(e) for e in eqs]
        ineqs = [normalize(i) for i in ineqs]
        for e in eqs:  # trivially unsatisfiable equalities
            if not any(e[:-1]) and e[-1] != 0:
                return Polyhedron.bottom(n)
        for i in ineqs:
            if not any(i[:-1]) and i[-1] < 0:
                return Polyhedron.bottom(n)
        positivity = (0,) * n + (1,)
        lines, rays = _dd(n + 1, eqs, [positivity] + ineqs)
        return Polyhedron._from_dd_generators(n, lines, rays)

    @staticmethod
    def from_generators(n, lines, rays):
        if not any(r[-1] > 0 for r in rays):
            return Polyhedron.bottom(n)
        ceqs, cineqs = _dd(n + 1, lines, rays)
        cineqs = [c for c in cineqs if any(c[:-1])]  # drop tautologies (e.g. 1 >= 0)
        lines, rays = _dd(n + 1, ceqs, [(0,) * n + (1,)] + cineqs)
        return Polyhedron(n, ceqs, cineqs, lines, rays, False)

    @staticmethod
    def _from_dd_generators(n, lines, rays):
        if not any(r[-1] > 0 for r in rays):
            return Polyhedron.bottom(n)
        ceqs, cineqs = _dd(n + 1, lines, rays)
        cineqs = [c for c in cineqs if any(c[:-1])]
        return Polyhedron(n, ceqs, cineqs, lines, rays, False)

    # predicates

    def is_bottom(self):
        return self.empty

    def is_universe(self):
        return not self.empty and not self.eqs and not self.ineqs

    def satisfies(self, a, eq=False):
        """Whether every point of the polyhedron satisfies a.x + c >= 0 (or = 0)."""
        if self.empty:
            return True
        for l in self.lines:
            if dot(a, l) != 0:
                return False
        for r in self.rays:
            s = dot(a, r)
            if s < 0 or (eq and s != 0):
                return False
        return True

    def is_leq(self, other):
        if self.empty:
            return True
        if other.empty:
            return False
        return (all(self.satisfies(e, True) for e in other.eqs)
                and all(self.satisfies(i) for i in other.ineqs))

    def is_eq(self, other):
        return self.is_leq(other) and other.is_leq(self)

    # lattice operations

    def meet(self, other):
        if self.empty:
            return self
        if other.empty:
            return other
        return Polyhedron.from_constraints(self.n, self.eqs + other.eqs, self.ineqs + other.ineqs)

    def meet_constraints(self, eqs=(), ineqs=()):
        if self.empty:
            return self
        return Polyhedron.from_constraints(self.n, self.eqs + list(eqs), self.ineqs + list(ineqs))

    def join(self, other):
        if self.empty:
            return other
        if other.empty:
            return self
        return Polyhedron.from_generators(self.n, self.lines + other.lines, self.rays + other.rays)

    def widen(self, other):
        """Standard widening (Cousot & Halbwachs 1978, as in NewPolka): keeps
        the constraints of self that are still satisfied by other (i.e., the
        stable ones), plus the constraints of other that are equivalent to a
        constraint of self (same saturated generators of self), so that the
        result does not depend on the representation of self."""
        if self.empty:
            return other
        if other.empty:
            return self
        c1 = self.constraint_list()
        c2 = other.constraint_list()
        gens = self.rays

        def saturation(a):
            return frozenset(i for i, g in enumerate(gens) if dot(a, g) == 0)

        kept = [c for c in c1 if other.satisfies(c)]
        sats = {saturation(c) for c in c1}
        for c in c2:
            if c not in kept and saturation(c) in sats and all(dot(c, l) == 0 for l in self.lines):
                kept.append(c)
        return Polyhedron.from_constraints(self.n, [], kept)

    # dimensions

    def add_dimensions(self, k):
        """Appends k unconstrained dimensions."""
        if self.empty:
            return Polyhedron.bottom(self.n + k)
        z = (0,) * k

        def ext(v):
            return v[:-1] + z + v[-1:]

        n = self.n + k
        lines = [ext(l) for l in self.lines]
        for i in range(self.n, n):
            lines.append(tuple(1 if j == i else 0 for j in range(n + 1)))
        return Polyhedron(n, [ext(e) for e in self.eqs], [ext(i) for i in self.ineqs],
                          lines, [ext(r) for r in self.rays], False)

    def remove_dimensions(self, k):
        """Projects away the last k dimensions."""
        n = self.n - k
        if self.empty:
            return Polyhedron.bottom(n)
        if k == 0:
            return self

        def proj(v):
            return v[:n] + v[-1:]

        lines = [p for p in (proj(l) for l in self.lines) if any(p)]
        rays = [p for p in (proj(r) for r in self.rays) if any(p)]
        return Polyhedron.from_generators(n, lines, rays)

    # transfer functions

    def assign(self, i, vec, den=1):
        """x_i := (a_1*x_1 + ... + a_n*x_n + c) / den, with vec = (a_1, ..., a_n, c)."""
        if self.empty:
            return self

        def tr(g):
            v = dot(vec, g)
            return normalize(tuple((den * x if j != i else v) for j, x in enumerate(g)))

        lines = [p for p in (tr(l) for l in self.lines) if any(p)]
        rays = [p for p in (tr(r) for r in self.rays) if any(p)]
        return Polyhedron.from_generators(self.n, lines, rays)

    def substitute(self, i, vec):
        """Pre-image of x_i := vec (homogenized integer vector)."""
        if self.empty:
            return self

        def sub(a):
            ai = a[i]
            if ai == 0:
                return a
            return tuple((x if j != i else 0) + ai * y for j, (x, y) in enumerate(zip(a, vec)))

        return Polyhedron.from_constraints(self.n, [sub(e) for e in self.eqs], [sub(c) for c in self.ineqs])

    def forget(self, i):
        if self.empty:
            return self
        line = tuple(1 if j == i else 0 for j in range(self.n + 1))
        return Polyhedron.from_generators(self.n, self.lines + [line], self.rays)

    # queries

    def bounds(self, a):
        """Bounds (lo, hi) of a.x + c over the polyhedron (None for infinity)."""
        if self.empty:
            return None
        lo = hi = None
        lo_inf = hi_inf = False
        for l in self.lines:
            if dot(a, l) != 0:
                return (None, None)
        for r in self.rays:
            s = dot(a, r)
            if r[-1] == 0:
                if s > 0:
                    hi_inf = True
                elif s < 0:
                    lo_inf = True
            else:
                v = Fraction(s, r[-1])
                if lo is None or v < lo:
                    lo = v
                if hi is None or v > hi:
                    hi = v
        return (None if lo_inf else lo, None if hi_inf else hi)

    def constraint_list(self):
        """Inequalities, with each equality expanded into two inequalities."""
        res = []
        for e in self.eqs:
            res.append(e)
            res.append(tuple(-x for x in e))
        res.extend(self.ineqs)
        return res

    def __repr__(self):
        if self.empty:
            return 'Polyhedron(bottom)'
        return 'Polyhedron(eqs=%r, ineqs=%r)' % (self.eqs, self.ineqs)
